// Перевод сухих чисел в понятные сравнения: «это три марафона», «0,3% пути до Луны».
// У каждой метрики свой справочник. Из сравнений подходящего масштаба выбирается одно, и выбор
// меняется, только когда число заметно выросло (~18%), — чтобы плитка не мигала каждую минуту.
import { plural } from './format';

/** Эталон: величина в единицах метрики, склонения для «N раз» и родительный падеж для долей. */
export interface Ref {
  v: number;
  /** «1 автобус», «2 автобуса», «5 автобусов»; без форм эталон годится только для долей. */
  forms?: [one: string, few: string, many: string];
  /** После дроби — родительный ед. ч.: «1,5 Эйфелевой башни». По умолчанию форма «2 …». */
  gen?: string;
  /** Хвост после «N раз»: «… в длину»; к долям не добавляется. */
  tail?: string;
  /** «12% пути до Луны»; без него доли не показываются. */
  part?: string;
  /** Меньшая доля, которую ещё стоит показывать (по умолчанию 20%: «2% поля» не смешно, «0,01% пути до Марса» — да). */
  min?: number;
}

const MAX_TIMES = 40;

const fmt1 = (x: number) => (x >= 10 ? Math.round(x).toLocaleString('ru-RU') : x.toFixed(1).replace('.', ',').replace(',0', ''));

function times(x: number, [one, few, many]: [string, string, string], gen = few) {
  const n = x >= 10 ? Math.round(x) : Math.round(x * 10) / 10;
  if (!Number.isInteger(n)) return `${fmt1(n)} ${gen}`; // «1,5 марафона»
  return `${n.toLocaleString('ru-RU')} ${plural(n, one, few, many)}`;
}

/** 37% / 4,2% / 0,35% / 0,01%. */
export function pct(ratio: number): string {
  const p = ratio * 100;
  const s = p >= 10 ? String(Math.round(p)) : p >= 1 ? p.toFixed(1).replace(/\.0$/, '') : p.toFixed(2).replace(/0$/, '');
  return `${s.replace('.', ',')}%`;
}

// 99,7% показываем как «1 …», а не «100% …»
const whole = (r: Ref, ratio: number) => ratio >= 1 || (!!r.forms && ratio >= 0.995);

function say(r: Ref, ratio: number): string {
  return whole(r, ratio) ? times(Math.max(1, ratio), r.forms!, r.gen) + (r.tail ?? '') : `${pct(ratio)} ${r.part}`;
}

/** Сравнение величины `x` с одним из эталонов; `undefined`, если не подошёл ни один. */
export function compare(x: number, refs: Ref[]): string | undefined {
  const fits = refs.filter((r) => {
    const ratio = x / r.v;
    if (whole(r, ratio)) return !!r.forms && ratio <= MAX_TIMES;
    return !!r.part && Math.round(ratio * 10_000) >= Math.round((r.min ?? 0.2) * 10_000);
  });
  if (!fits.length) {
    // больше самого крупного эталона в 40 раз — всё равно считаем в нём
    const big = refs.filter((r) => r.forms && x >= r.v).at(-1);
    return big && say(big, x / big.v);
  }
  const step = Math.floor(Math.log(x) * 6); // ступени по ~18%
  const r = fits[(Math.imul(step, 0x9e3779b1) >>> 0) % fits.length];
  return say(r, x / r.v);
}

